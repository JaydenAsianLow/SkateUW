// Converts the OpenStreetMap extracts in public/map/ into src/display/redSquare/osm.js.
//
//   node scripts/osm-to-level.mjs
//
// Coordinates: 1 unit = 1 m, origin in Red Square, +x = east, +z = south (so -z is north,
// matching Three.js "forward"). Map data © OpenStreetMap contributors (ODbL).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (f) => JSON.parse(readFileSync(join(root, 'public/map', f), 'utf8')).elements;
const elements = [...load('red-square.json'), ...load('red-square-relations.json'), ...load('rv.json')];

// Origin near the middle of the plaza. Meters per degree at this latitude (WGS84).
const LAT0 = 47.656;
const LON0 = -122.3095;
const phi = (LAT0 * Math.PI) / 180;
const M_LAT = 111132.954 - 559.822 * Math.cos(2 * phi) + 1.175 * Math.cos(4 * phi);
const M_LON = 111412.84 * Math.cos(phi) - 93.5 * Math.cos(3 * phi);
const toXZ = (lat, lon) => [+((lon - LON0) * M_LON).toFixed(2), +(-(lat - LAT0) * M_LAT).toFixed(2)];

// Drop the closing duplicate, near-duplicate and almost-collinear points.
function simplify(pts, minLen = 0.6, maxDev = 0.15) {
  let p = pts.slice();
  if (p.length > 2 && p[0][0] === p.at(-1)[0] && p[0][1] === p.at(-1)[1]) p.pop();
  let changed = true;
  while (changed && p.length > 3) {
    changed = false;
    for (let i = 0; i < p.length && p.length > 3; i++) {
      const a = p[(i - 1 + p.length) % p.length];
      const b = p[i];
      const c = p[(i + 1) % p.length];
      const ab = Math.hypot(b[0] - a[0], b[1] - a[1]);
      const ac = Math.hypot(c[0] - a[0], c[1] - a[1]) || 1;
      const dev = Math.abs((c[0] - a[0]) * (a[1] - b[1]) - (a[0] - b[0]) * (c[1] - a[1])) / ac;
      if (ab < minLen || dev < maxDev) {
        p.splice(i, 1);
        changed = true;
        i--;
      }
    }
  }
  return p;
}

const area = (p) => p.reduce((s, a, i) => { const b = p[(i + 1) % p.length]; return s + a[0] * b[1] - b[0] * a[1]; }, 0) / 2;
const centroid = (p) => p.reduce((s, a) => [s[0] + a[0] / p.length, s[1] + a[1] / p.length], [0, 0]).map((v) => +v.toFixed(1));

const byId = new Map(elements.map((e) => [`${e.type}/${e.id}`, e]));
const wayPts = (id) => simplify(byId.get(`way/${id}`).geometry.map((g) => toXZ(g.lat, g.lon)));

// --- Plaza outline (the member way of the "Red Square" relation)
const PLAZA = wayPts(1491155049);

// --- Buildings. Heights: OSM height, else levels × 4.2 m (older campus floors are tall).
const LEVEL_H = 4.2;
const HEIGHTS = {
  // Estimated from photos/knowledge where OSM has no height. Verify on site (MAP.md §12).
  'Kane Hall': 17,
  'Odegaard Undergraduate Library': 15,
  'Meany Hall': 14,
  'Gerberding Hall': 18,
};
const seen = new Set();
const buildings = [];
for (const e of elements) {
  if (e.type !== 'way' || !e.geometry || seen.has(e.id)) continue;
  const t = e.tags ?? {};
  if (!t.building || t.building === 'roof' || t.building === 'industrial') continue;
  seen.add(e.id);
  const pts = simplify(e.geometry.map((g) => toXZ(g.lat, g.lon)));
  if (pts.length < 3 || Math.abs(area(pts)) < 30) continue;
  const levels = +(t['building:levels'] ?? 0) || 3;
  const height = HEIGHTS[t.name] ?? (+t.height || levels * LEVEL_H);
  buildings.push({ id: e.id, name: t.name ?? null, height: +height.toFixed(1), pts });
}
// Suzzallo is a multipolygon relation; its outer way carries no tags of its own.
buildings.push({ id: 222831555, name: 'Suzzallo Library', height: 22, pts: wayPts(222831555) });

// Brick ventilation monoliths (OSM: three 'building' ways tagged height=42, most likely feet).
const MONOLITH_IDS = [445398675, 445398676, 445398677];
const MONOLITHS = MONOLITH_IDS.map((id) => ({ pts: wayPts(id), height: 13 }));
const BUILDINGS = buildings.filter((b) => !MONOLITH_IDS.includes(b.id));

// --- Points of interest
const node = (id) => { const n = byId.get(`node/${id}`); return toXZ(n.lat, n.lon); };
const fountain = byId.get('way/' + elements.find((e) => e.tags?.name === 'Drumheller Fountain').id).geometry.map((g) => toXZ(g.lat, g.lon));
const fc = centroid(fountain);
const POI = {
  brokenObelisk: node(2677761043),
  georgeWashington: node(2672133045),
  drumheller: { center: fc, radius: +(fountain.reduce((s, p) => s + Math.hypot(p[0] - fc[0], p[1] - fc[1]), 0) / fountain.length).toFixed(1) },
};

const out = `// GENERATED by scripts/osm-to-level.mjs from public/map/*.json. Do not edit by hand.
// Map data © OpenStreetMap contributors, available under the Open Database License (ODbL).
// Units: meters. Origin (${LAT0}, ${LON0}) in Red Square. +x = east, +z = south, -z = north.

export const ORIGIN = { lat: ${LAT0}, lon: ${LON0} };
export const PLAZA = ${JSON.stringify(PLAZA)};
export const BUILDINGS = ${JSON.stringify(BUILDINGS, null, 0).replace(/\},\{/g, '},\n  {')};
export const MONOLITHS = ${JSON.stringify(MONOLITHS)};
export const POI = ${JSON.stringify(POI)};
`;
mkdirSync(join(root, 'src/display/redSquare'), { recursive: true });
writeFileSync(join(root, 'src/display/redSquare/osm.js'), out);
console.log(`plaza ${PLAZA.length} pts, ${BUILDINGS.length} buildings, ${MONOLITHS.length} monoliths`, POI);
