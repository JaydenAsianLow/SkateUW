import Atmosphere from './Atmosphere.jsx';
import { Benches, LampPosts } from './Props.jsx';
import { Trees } from './Trees.jsx';
import Ground from './redSquare/Ground.jsx';
import Suzzallo from './redSquare/Suzzallo.jsx';
import { Backdrop, MidBuilding, Monolith } from './redSquare/Footprints.jsx';
import { BrokenObelisk, Drumheller, GeorgeWashington, MountRainier } from './redSquare/Landmarks.jsx';
import { BACKDROP, BENCHES, LAMPS, MID, TREES } from './redSquare/layout.js';
import { MONOLITHS } from './redSquare/osm.js';

// Level 1: Red Square (Central Plaza), University of Washington. See MAP.md.
// Building footprints, the plaza outline and landmark positions come from OpenStreetMap
// (src/display/redSquare/osm.js, generated by scripts/osm-to-level.mjs). 1 unit = 1 m, north = -z.
export default function World() {
  return (
    <>
      <Atmosphere />
      <Ground />

      {/* East: Suzzallo Library, the hero building */}
      <Suzzallo />
      {/* Kane (NE), Odegaard (NW), Meany (SW), Gerberding (SE) */}
      {MID.map(({ b, style }) => (
        <MidBuilding key={b.id} pts={b.pts} height={b.height} style={style} />
      ))}
      <Backdrop buildings={BACKDROP} />

      {/* Landmarks */}
      {MONOLITHS.map((mo, i) => (
        <Monolith key={i} pts={mo.pts} height={mo.height} />
      ))}
      <BrokenObelisk />
      <GeorgeWashington />
      <Drumheller />
      <MountRainier />

      <LampPosts positions={LAMPS} />
      <Benches benches={BENCHES} />
      <Trees trees={TREES} />
    </>
  );
}
