import Atmosphere from './Atmosphere.jsx';
import { Benches, LampPosts } from './Props.jsx';
import { Trees } from './Trees.jsx';
import Ground from './redSquare/Ground.jsx';
import { Backdrop, MidBuilding } from './redSquare/Footprints.jsx';
import { Drumheller, GeorgeWashington, MountRainier } from './redSquare/Landmarks.jsx';
import { BACKDROP, BENCHES, LAMPS, MID, TREES } from './redSquare/layout.js';
import { Facade, GlbPiece, preloadFacades } from './redSquare/Glb.jsx';

preloadFacades();

// Level 1: Red Square (Central Plaza), University of Washington. See MAP.md.
// Building footprints, the plaza outline and landmark positions come from OpenStreetMap
// (src/display/redSquare/osm.js, generated by scripts/osm-to-level.mjs). 1 unit = 1 m, north = -z.
// The faces of the buildings that look onto the plaza, the monoliths, Broken Obelisk and the planter slabs are
// modelled in Blender from the photos in "Red Square/" (art/scripts/2x_*.py -> public/models/redsquare/).
export default function World() {
  return (
    <>
      <Atmosphere />
      <Ground />

      {/* The building masses (OSM footprints), with the plaza fronts modelled in Blender on top */}
      {MID.map(({ b, style }) => (
        <MidBuilding key={b.id} pts={b.pts} height={b.height} style={style} />
      ))}
      <Backdrop buildings={BACKDROP} />
      <Facade name="suzzallo" />
      <Facade name="kane" />
      <Facade name="odegaard" />
      <Facade name="meany" />
      <Facade name="gerberding" />
      {/* Monoliths with banners, Broken Obelisk on its granite bank, the planter slabs (world coordinates) */}
      <GlbPiece name="landmarks" />

      <GeorgeWashington />
      <Drumheller />
      <MountRainier />

      <LampPosts positions={LAMPS} />
      <Benches benches={BENCHES} />
      <Trees trees={TREES} />
    </>
  );
}
